# ---------------------------------------------------------------------------
# Data model
# ---------------------------------------------------------------------------

# URL segments that identify a site's root page (grouped as one feature).
ROOT_PAGES = {"", "index.html", "index.htm", "index.php",
              "default.html", "default.htm", "home"}


def group_key(url: str) -> str:
    seg = urllib.parse.urlparse(url).path.strip("/").split("/")[0].lower()
    return "(root)" if seg in ROOT_PAGES else seg


@dataclass
class PageRecord:
    url: str
    title: str
    depth: int
    h1: str = ""
    n_links: int = 0
    n_buttons: int = 0
    n_inputs: int = 0
    n_forms: int = 0
    forms: list = field(default_factory=list)
    screenshot: str = ""


@dataclass
class Transition:
    frm: str
    action: str
    to: str


# ---------------------------------------------------------------------------
# Explorer
# ---------------------------------------------------------------------------

class Explorer:
    def __init__(self, args):
        self.args = args
        self.start = normalize_url(args.url)
        parsed = urllib.parse.urlparse(self.start)
        self.origin = f"{parsed.scheme}://{parsed.netloc}"
        self.pages: dict[str, PageRecord] = {}
        self.transitions: list[Transition] = []
        self.skipped: list[dict] = []
        self.blocked: list[dict] = []
        self.rp = urllib.robotparser.RobotFileParser()
        if args.respect_robots:
            try:
                self.rp.set_url(urllib.parse.urljoin(self.origin, "/robots.txt"))
                self.rp.read()
            except Exception:
                pass
        self.shots_dir = Path(args.output_dir) / "shots"
        self.shots_dir.mkdir(parents=True, exist_ok=True)
        self._shot_n = 0

    def resolve_proxy(self) -> dict | None:
        """Proxy for the browser, from --proxy or standard env vars.

        Keeps credentials out of skill files: they stay in the environment.
        """
        raw = (self.args.proxy
               or os.environ.get("HTTPS_PROXY")
               or os.environ.get("https_proxy")
               or os.environ.get("HTTP_PROXY")
               or os.environ.get("http_proxy"))
        if not raw:
            return None
        u = urllib.parse.urlparse(raw)
        server = f"{u.scheme or 'http'}://{u.hostname}:{u.port or 8080}"
        d = {"server": server}
        if u.username:
            d["username"] = urllib.parse.unquote(u.username)
        if u.password:
            d["password"] = urllib.parse.unquote(u.password)
        bypass = os.environ.get("NO_PROXY") or os.environ.get("no_proxy")
        if bypass:
            # Playwright wants comma-separated hosts, no CIDR brackets.
            hosts = [h.strip().strip("[]") for h in bypass.split(",") if h.strip()]
            if hosts:
                d["bypass"] = ",".join(hosts)
        return d

    # -- seeds ------------------------------------------------------------
    def sitemap_seeds(self) -> list[str]:
        seeds = []
        for name in ("sitemap.xml", "sitemap_index.xml"):
            try:
                import urllib.request
                with urllib.request.urlopen(
                    urllib.parse.urljoin(self.origin, name), timeout=10
                ) as resp:
                    body = resp.read().decode("utf-8", "ignore")
                seeds += re.findall(r"<loc>\s*([^<\s]+)\s*</loc>", body)[:200]
            except Exception:
                pass
        return [normalize_url(s) for s in seeds if s.startswith(self.origin)]

    # -- main loop --------------------------------------------------------
    def run(self):
        from playwright.sync_api import sync_playwright

        seeds = [self.start] + self.sitemap_seeds()
        queue: list[tuple[str, int]] = []
        for s in seeds:
            if s not in self.pages:
                queue.append((s, 0))

        with sync_playwright() as pw:
            browser = pw.chromium.launch(headless=True)
            ctx_kwargs = {}
            proxy = self.resolve_proxy()
            if proxy:
                ctx_kwargs["proxy"] = proxy
            if self.args.auth_state:
                ctx_kwargs["storage_state"] = self.args.auth_state
            context = browser.new_context(**ctx_kwargs)
            page = context.new_page()
            page.set_default_timeout(20000)

            while queue and len(self.pages) < self.args.max_pages:
                url, depth = queue.pop(0)
                if url in self.pages or depth > self.args.max_depth:
                    continue
                if self.args.respect_robots and not self.rp.can_fetch("*", url):
                    self.blocked.append({"url": url, "reason": "robots.txt"})
                    continue
                try:
                    self.visit(page, url, depth, queue)
                except Exception as e:  # noqa: BLE001 - keep crawling on errors
                    self.blocked.append({"url": url, "reason": f"error: {e}"})
                time.sleep(self.args.delay_ms / 1000.0)

            browser.close()

    def visit(self, page, url: str, depth: int, queue: list):
        page.goto(url, wait_until="domcontentloaded")
        try:
            page.wait_for_load_state("networkidle", timeout=8000)
        except Exception:
            pass

        norm = normalize_url(page.url)
        if norm in self.pages:
            return

        # Bot wall / CAPTCHA detection: record and stop touching this page.
        html_head = page.content()[:4000].lower()
        if any(k in html_head for k in ("captcha", "cf-challenge", "are you a robot",
                                       "verify you are human", "datadome", "perimeterx")):
            self.blocked.append({"url": norm, "reason": "bot wall / CAPTCHA detected"})
            return

        data = page.evaluate(ELEMENT_ENUM_JS)
        elements = data["elements"]
        forms = data["forms"]

        links = [e for e in elements if e["tag"] == "a" and e["href"]]
        buttons = [e for e in elements if e["tag"] in ("button",) or "button" in e.get("role", "")]
        inputs = [e for e in elements if e["tag"] in ("input", "select", "textarea")]

        self._shot_n += 1
        shot_name = f"shots/p{self._shot_n:03d}.png"
        page.screenshot(path=str(self.shots_dir / f"p{self._shot_n:03d}.png"),
                        full_page=False)

        rec = PageRecord(
            url=norm,
            title=page.title()[:120],
            depth=depth,
            h1=data.get("h1", ""),
            n_links=len(links),
            n_buttons=len(buttons),
            n_inputs=len(inputs),
            n_forms=len(forms),
            forms=forms,
            screenshot=shot_name,
        )
        self.pages[norm] = rec

        # Queue same-origin links discovered on the page.
        # Never even *visit* links whose label looks destructive: some sites
        # trigger deletes/purchases on plain GET.
        for e in links:
            href = urllib.parse.urljoin(norm, e["href"])
            if not href.startswith(self.origin):
                continue
            if href.lower().startswith(("mailto:", "tel:", "javascript:")):
                continue
            label = e["label"] or href
            if is_dangerous(label):
                self.skipped.append({"url": norm,
                                     "action": f"follow link '{label[:60]}'",
                                     "reason": "destructive pattern"})
                continue
            target = normalize_url(href)
            if target not in self.pages and not any(q[0] == target for q in queue):
                queue.append((target, depth + 1))

        # Explore mode: safe clicks on same-origin links/buttons.
        if self.args.mode == "explore":
            self.safe_clicks(page, norm, elements, queue)

    def safe_clicks(self, page, norm: str, elements: list, queue: list):
        clickables = [e for e in elements
                      if e["tag"] in ("a", "button") and (e["label"] or e["href"])]
        tried = 0
        for e in clickables:
            if tried >= self.args.max_clicks_per_page:
                break
            label = e["label"] or e["href"]
            if is_dangerous(label):
                self.skipped.append({"url": norm, "action": f"click '{label}'",
                                     "reason": "destructive pattern"})
                continue
            href = e.get("href", "")
            if href:
                target = normalize_url(urllib.parse.urljoin(norm, href))
                if target.startswith(self.origin) and target not in self.pages:
                    self.transitions.append(
                        Transition(norm, f"click link '{label[:60]}'", target))
                    if not any(q[0] == target for q in queue):
                        queue.append((target, self.pages[norm].depth + 1))
                tried += 1
            # Buttons without href (JS-driven): click and observe URL change.
            elif e["tag"] == "button":
                try:
                    before = normalize_url(page.url)
                    page.get_by_role("button", name=e["label"][:60]).first.click(
                        timeout=5000)
                    page.wait_for_timeout(1500)
                    after = normalize_url(page.url)
                    if after != before and after.startswith(self.origin):
                        self.transitions.append(
                            Transition(norm, f"click button '{label[:60]}'", after))
                        if after not in self.pages and not any(q[0] == after for q in queue):
                            queue.append((after, self.pages[norm].depth + 1))
                        page.go_back(wait_until="domcontentloaded")
                except Exception as ex:  # noqa: BLE001
                    self.skipped.append({"url": norm, "action": f"click button '{label[:60]}'",
                                         "reason": f"click failed: {ex}"})
                tried += 1

    # -- feature extraction ------------------------------------------------
    def _dedupe_name(self, name: str, name_en: str, used: set) -> tuple:
        if name not in used:
            used.add(name)
            return name, name_en
        i = 2
        while f"{name} ({i})" in used:
            i += 1
        final = f"{name} ({i})"
        used.add(final)
        return final, f"{name_en} ({i})"

    def semantic_name(self, key: str, urls: list, used: set) -> tuple:
        """(display, english) feature name.

        Priority: password field -> root page -> keyword match on
        h1/title/url -> most common h1 -> prettified URL segment.
        Never returns a bare filename like 'index.html'.
        """
        lang_idx = 1 if self.args.lang == "zh" else 0
        # Strongest signal: a password field means a login form.
        for u in urls:
            for form in self.pages[u].forms:
                if any(f.get("type") == "password" for f in form["fields"]):
                    names = ("authentication", "用户登录")
                    return self._dedupe_name(names[lang_idx], names[0], used)
        if key == "(root)":
            names = ("homepage", "首页")
            return self._dedupe_name(names[lang_idx], names[0], used)
        blob = " ".join(
            f"{self.pages[u].h1} {self.pages[u].title} {u}" for u in urls
        ).lower()
        for pat, names in FEATURE_KEYWORDS:
            if re.search(pat, blob):
                return self._dedupe_name(names[lang_idx], names[0], used)
        h1s = [self.pages[u].h1 for u in urls if self.pages[u].h1]
        if h1s:
            top = max(set(h1s), key=h1s.count)
            return self._dedupe_name(top, top.lower(), used)
        pretty = re.sub(r"\.(html?|php|aspx|jsp)$", "", key)
        pretty = pretty.replace("-", " ").replace("_", " ").strip() or key
        return self._dedupe_name(pretty, pretty, used)

    def extract_features(self) -> list[dict]:
        """Cluster pages into features by URL path prefix + forms present."""
        groups: dict[str, dict] = {}
        for url, rec in self.pages.items():
            path = group_key(url)
            g = groups.setdefault(path, {"key": path, "urls": [], "forms": [],
                                         "inputs": set(), "actions": set()})
            g["urls"].append(url)
            for f in rec.forms:
                g["forms"].append({"page": url, "fields": f["fields"]})
                for fld in f["fields"]:
                    g["inputs"].add(fld["name"])
        for t in self.transitions:
            path = group_key(t.frm)
            if path in groups:
                groups[path]["actions"].add(t.action)
        features = []
        used_names: set = set()
        for key, g in sorted(groups.items()):
            name, name_en = self.semantic_name(key, g["urls"], used_names)
            if self.args.lang != "zh":
                name = name_en
            features.append({
                "name": name,
                "name_en": name_en,
                "entry_urls": sorted(g["urls"])[:5],
                "page_count": len(g["urls"]),
                "inputs": sorted(g["inputs"]),
                "forms": g["forms"],
                "observed_actions": sorted(g["actions"])[:20],
            })
        return features

    # -- outputs -----------------------------------------------------------
    def write_outputs(self):
        out = Path(self.args.output_dir)
        out.mkdir(parents=True, exist_ok=True)
        features = self.extract_features()

        with open(out / "features.json", "w", encoding="utf-8") as f:
            json.dump({
                "target": self.origin,
                "mode": self.args.mode,
                "lang": self.args.lang,
                "pages": [asdict(p) for p in self.pages.values()],
                "features": features,
                "transitions": [asdict(t) for t in self.transitions],
                "skipped_actions": self.skipped,
                "blocked_pages": self.blocked,
            }, f, ensure_ascii=False, indent=2)

        with open(out / "use-cases.md", "w", encoding="utf-8") as f:
            S = STRINGS[self.args.lang]
            mode_name = S.get(f"mode_{self.args.mode}", self.args.mode)
            f.write(S["uc_title"].format(target=self.origin) + "\n")
            f.write(S["uc_note"].format(mode=mode_name) + "\n\n")
            for n, feat in enumerate(features, 1):
                uid = f"UC-{n:02d}"
                # A feature counts as verified only if at least one transition
                # starting from its pages was actually observed.
                verified = any(t.frm in feat["entry_urls"] for t in self.transitions)
                mark = S["verified"] if verified else S["unverified"]
                f.write(f"## {uid}: {feat['name']}\n\n")
                f.write(f"{S['entries']} {', '.join(feat['entry_urls'][:3])}\n\n")
                if feat["observed_actions"]:
                    f.write(S["evidence"] + "\n")
                    for a in feat["observed_actions"][:8]:
                        f.write(f"- {a}\n")
                    f.write("\n")

                sub = 1
                f.write(f"### {uid}-{sub} {S['happy']} {mark}\n")
                f.write("```gherkin\n")
                f.write(f"Feature: {feat['name']}\n")
                f.write(f"  Scenario: {S['scenario_happy'].format(name=feat['name'])}\n")
                f.write(f"    Given {S['given_on'].format(url=feat['entry_urls'][0])}\n")
                if feat["observed_actions"]:
                    f.write(f"    When {S['when_observed'].format(action=feat['observed_actions'][0])}\n")
                elif feat["inputs"]:
                    f.write(f"    When {S['when_fill'].format(fields=', '.join(feat['inputs'][:5]))}\n")
                    f.write(f"    And {S['and_submit']}\n")
                else:
                    f.write(f"    When {S['when_cta']}\n")
                f.write(f"    Then {S['then_result']}\n")
                f.write(f"    And {S['and_no_error']}\n```\n\n")

                req_fields = [fld["name"] for form in feat["forms"]
                              for fld in form["fields"] if fld.get("required")]
                if req_fields:
                    sub += 1
                    f.write(f"### {uid}-{sub} {S['missing']} {S['unverified']}\n")
                    f.write("```gherkin\n")
                    f.write(f"  Scenario: {S['scenario_missing']}\n")
                    f.write(f"    Given {S['given_on'].format(url=feat['entry_urls'][0])}\n")
                    f.write(f"    When {S['when_empty']}\n")
                    f.write(f"    Then {S['then_validation']}\n")
                    f.write(f"    And {S['and_not_submitted']}\n```\n\n")

                text_inputs = [fld["name"] for form in feat["forms"]
                               for fld in form["fields"]
                               if fld.get("type") in ("text", "email", "tel", "url", "")]
                if text_inputs:
                    sub += 1
                    f.write(f"### {uid}-{sub} {S['invalid']} {S['unverified']}\n")
                    f.write("```gherkin\n")
                    f.write(f"  Scenario: {S['scenario_invalid']}\n")
                    f.write(f"    Given {S['given_on'].format(url=feat['entry_urls'][0])}\n")
                    f.write(f"    When {S['when_invalid']}\n")
                    f.write(f"    Then {S['then_format']}\n```\n\n")

        with open(out / "report.md", "w", encoding="utf-8") as f:
            S = STRINGS[self.args.lang]
            f.write(S["rp_title"].format(target=self.origin) + "\n\n")
            f.write(f"- {S['rp_mode']}: {self.args.mode}\n")
            f.write(f"- {S['rp_pages']}: {len(self.pages)} ({S['rp_limit']} {self.args.max_pages})\n")
            f.write(f"- {S['rp_features']}: {len(features)}\n")
            f.write(f"- {S['rp_transitions']}: {len(self.transitions)}\n")
            f.write(f"- {S['rp_skipped']}: {len(self.skipped)}\n")
            f.write(f"- {S['rp_blocked']}: {len(self.blocked)}\n\n")
            if self.blocked:
                f.write(S["rp_blocked_h"] + "\n")
                for b in self.blocked:
                    f.write(f"- {b['url']}: {b['reason']}\n")
                f.write("\n")
            if self.skipped:
                f.write(S["rp_skipped_h"] + "\n")
                for s in self.skipped[:30]:
                    f.write(f"- {s['url']} — {s['action']}: {s['reason']}\n")
        print(f"Done: {len(self.pages)} pages, {len(features)} features "
              f"-> {out.resolve()}")


