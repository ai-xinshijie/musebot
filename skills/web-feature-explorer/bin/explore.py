def parse_args(argv=None):
    p = argparse.ArgumentParser(description="Autonomous web UI explorer")
    p.add_argument("--url", required=True, help="Start URL, e.g. https://example.com")
    p.add_argument("--mode", choices=["discover", "explore"], default="discover",
                   help="discover = read-only crawl; explore = also safe-clicks")
    p.add_argument("--max-pages", type=int, default=50)
    p.add_argument("--max-depth", type=int, default=3)
    p.add_argument("--max-clicks-per-page", type=int, default=10,
                   help="cap on safe clicks per page in explore mode")
    p.add_argument("--delay-ms", type=int, default=800,
                   help="politeness delay between page visits")
    p.add_argument("--output-dir", default="./out",
                   help="where features.json / use-cases.md / report.md go")
    p.add_argument("--auth-state", default="",
                   help="Playwright storageState JSON for logged-in runs")
    p.add_argument("--respect-robots", action=argparse.BooleanOptionalAction,
                   default=True, help="honor robots.txt (default on)")
    p.add_argument("--proxy", default="",
                   help="proxy for the browser, e.g. http://user:pass@host:3128; "
                        "default: HTTPS_PROXY/https_proxy env var")
    p.add_argument("--lang", choices=["en", "zh"], default="en",
                   help="language of use-cases.md and report.md")
    return p.parse_args(argv)


def main(argv=None):
    args = parse_args(argv)
    exp = Explorer(args)
    exp.run()
    exp.write_outputs()


if __name__ == "__main__":
    sys.exit(main())
