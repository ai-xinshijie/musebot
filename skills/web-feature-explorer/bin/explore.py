#!/usr/bin/env python3
"""Autonomous web UI explorer.

Discovers routes and interactive elements of a website, builds a
page -> action -> page transition graph, clusters it into features, and
emits a feature inventory (features.json), Gherkin-style use cases
(use-cases.md), and an exploration report (report.md).

Usage:
    pip install playwright && playwright install chromium
    python3 explore.py --url https://example.com --mode discover \
        --max-pages 50 --output-dir ./out

Modes:
    discover  read-only crawl: visit pages, enumerate elements, take
              screenshots. Never clicks anything.
    explore   additionally performs SAFE clicks on same-origin links and
              buttons. Destructive actions (delete/pay/logout/...) are
              always skipped by pattern.
"""

