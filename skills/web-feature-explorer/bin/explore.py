# Actions that must never be triggered automatically.
DANGEROUS_PATTERNS = re.compile(
    r"delete|remove|destroy|erase|pay|checkout|purchase|buy\s*now|place\s*order|"
    r"submit.*payment|confirm.*payment|cancel.*(order|subscription)|unsubscribe|"
    r"close\s*account|log\s*out|sign\s*out|reset\s*password",
    re.IGNORECASE,
)

# Query params that don't change page identity (tracking / session noise).
NOISE_PARAMS = {
    "utm_source", "utm_medium", "utm_campaign", "utm_term", "utm_content",
    "gclid", "fbclid", "msclkid", "mc_cid", "mc_eid", "_ga", "ref", "sessionid",
    "sid", "phpsessid", "jsessionid",
}

ELEMENT_ENUM_JS = """() => {
  const els = [];
  const seen = new Set();
  const q = document.querySelectorAll(
    'a[href], button, input, select, textarea, [role="button"], [role="link"], [onclick]'
  );
  for (const el of q) {
    if (seen.has(el)) continue;
    seen.add(el);
    const r = el.getBoundingClientRect();
    if (r.width === 0 && r.height === 0) continue;  // hidden
    const label = (el.innerText || el.value || el.getAttribute('aria-label')
      || el.getAttribute('title') || el.getAttribute('placeholder') || '').trim()
      .replace(/\\s+/g, ' ').slice(0, 120);
    els.push({
      tag: el.tagName.toLowerCase(),
      type: el.getAttribute('type') || '',
      href: el.tagName === 'A' ? (el.getAttribute('href') || '') : '',
      label: label,
      name: el.getAttribute('name') || el.getAttribute('id') || '',
      required: !!el.required,
    });
  }
  const forms = [];
  for (const f of document.querySelectorAll('form')) {
    const fields = [];
    for (const inp of f.querySelectorAll('input, select, textarea')) {
      const lab = document.querySelector(`label[for="${inp.id}"]`);
      fields.push({
        name: inp.getAttribute('name') || inp.id || inp.type,
        type: inp.getAttribute('type') || inp.tagName.toLowerCase(),
        label: (lab ? lab.innerText.trim() : inp.getAttribute('placeholder') || '').slice(0, 80),
        required: !!inp.required,
      });
    }
    forms.push({
      action: f.getAttribute('action') || '',
      method: (f.getAttribute('method') || 'get').toLowerCase(),
      fields: fields,
    });
  }
  return { elements: els, forms: forms,
           h1: (document.querySelector('h1')?.innerText || '').trim()
                 .replace(/\\s+/g, ' ').slice(0, 120) };
}"""


def normalize_url(url: str) -> str:
    """Canonical page identity: drop fragment, noise params, trailing slash."""
    p = urllib.parse.urlparse(url)
    qs = urllib.parse.parse_qsl(p.query, keep_blank_values=True)
    qs = [(k, v) for k, v in qs if k.lower() not in NOISE_PARAMS]
    qs.sort()
    path = p.path.rstrip("/") or "/"
    return urllib.parse.urlunparse(
        (p.scheme.lower(), p.netloc.lower(), path, "", urllib.parse.urlencode(qs), "")
    )


def is_dangerous(text: str) -> bool:
    return bool(DANGEROUS_PATTERNS.search(text or ""))


